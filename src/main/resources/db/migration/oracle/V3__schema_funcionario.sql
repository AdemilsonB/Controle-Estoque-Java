CREATE TABLE funcionario (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100 CHAR) NOT NULL,
    sobrenome VARCHAR2(100 CHAR) NOT NULL,
    cpf VARCHAR2(11 CHAR) NOT NULL UNIQUE,
    email VARCHAR2(150 CHAR) NOT NULL UNIQUE,
    senha VARCHAR2(255 CHAR) NOT NULL,
    matricula VARCHAR2(20 CHAR) NOT NULL,
    data_admissao DATE NOT NULL,
    setor VARCHAR2(80 CHAR) NOT NULL,
    role VARCHAR2(20 CHAR) NOT NULL,
    logradouro VARCHAR2(150 CHAR) NOT NULL,
    numero VARCHAR2(20 CHAR) NOT NULL,
    bairro VARCHAR2(100 CHAR) NOT NULL,
    cidade VARCHAR2(100 CHAR) NOT NULL,
    estado VARCHAR2(2 CHAR) NOT NULL,
    cep VARCHAR2(9 CHAR) NOT NULL,
    ativo NUMBER(1,0) DEFAULT 1 NOT NULL,
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP NOT NULL
);
