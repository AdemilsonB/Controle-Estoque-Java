CREATE TABLE categoria (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(80 CHAR) NOT NULL UNIQUE,
    descricao VARCHAR2(255 CHAR)
);

CREATE TABLE colecao (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(80 CHAR) NOT NULL UNIQUE,
    descricao VARCHAR2(255 CHAR)
);
